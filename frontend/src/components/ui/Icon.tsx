export const Icon: React.FC<IconProps> = ({ name, className = '', size = 20, ...props }) => {
  if (!name) return null;
  const cleanName = String(name).trim().toLowerCase();
  const IconComponent = iconMap[cleanName] || Sparkles;
  return <IconComponent className={`shrink-0 inline-block ${className}`} size={size} {...props} />;
};

export default Icon;
